import { createDatabaseClient } from "@/lib/database-client"
import { expect, test } from "@playwright/test"

const database = createDatabaseClient()
test.afterAll(async () => { await database.$disconnect() })

test("Accounting confirms draft deletion and retrieves its unchanged unbilled time", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL) throw new Error("La preuve SQL navigateur exige la recette SQLite isolée")
  const invoiceId = `cinvoicerelease${info.project.name}`, id = `ctimerelease${info.project.name}`, errors: string[] = []
  const initial = await database.timeEntry.findUniqueOrThrow({ where: { id } })
  page.on("pageerror", error => errors.push(error.message))
  await page.context().clearCookies(); await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(`time-release-${info.project.name}@example.test`)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  expect((await page.goto(`/dashboard/factures/${invoiceId}`))?.status()).toBe(200)
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  const actions = page.getByRole("button", { name: "Actions", exact: true })
  await actions.click()
  await expect(actions).toHaveAttribute("aria-expanded", "true")
  await page.getByRole("menuitem", { name: "Supprimer", exact: true }).click()
  await page.getByRole("dialog").getByRole("button", { name: "Annuler", exact: true }).click()
  expect(await database.timeEntry.findUniqueOrThrow({ where: { id } })).toEqual(initial)
  expect(await database.invoice.count({ where: { id: invoiceId } })).toBe(1)
  await actions.click()
  await expect(actions).toHaveAttribute("aria-expanded", "true")
  await page.getByRole("menuitem", { name: "Supprimer", exact: true }).click()
  await page.getByRole("dialog").getByRole("button", { name: "Supprimer", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard/factures", { timeout: 60_000 })
  expect(await database.invoice.findUnique({ where: { id: invoiceId } })).toBeNull()
  expect(await database.invoiceLine.count({ where: { invoiceId } })).toBe(0)
  expect(await database.timeEntry.findUniqueOrThrow({ where: { id } })).toEqual({ ...initial, invoiceId: null })
  expect((await database.project.findUniqueOrThrow({ where: { id: initial.projectId } })).consumedCents).toBe(6250)
  expect(await database.auditLog.count({ where: { resourceId: invoiceId, action: "DELETE_INVOICE" } })).toBe(1)
  await page.goto("/dashboard/factures/temps-non-facture")
  await expect(page.getByText("FICTIONAL-RELEASE-TIME", { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
