import { createDatabaseClient } from "@/lib/database-client"
import { expect, test } from "@playwright/test"
import { hashPassword } from "../../src/lib/auth/password-core"
import { createOperationsDashboardFixture } from "../helpers/operations-dashboard-fixture"

test("edits and retires assets without losing history or a refused creation form", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette Sites et parc exige une SQLite fictive isolée")
  const db = createDatabaseClient()
  const fixture = await createOperationsDashboardFixture(db)
  try {
    const password = process.env.E2E_USER_PASSWORD || "RecetteSolide2026"
    await db.user.update({ where: { id: fixture.user.id }, data: { emailVerified: new Date(), passwordHash: await hashPassword(password) } })
    await db.saasSubscription.create({ data: { companyId: fixture.companyId, plan: "RESEAU", status: "ACTIVE", seatQuantity: 30 } })
    await db.customerSite.createMany({ data: Array.from({ length: 201 }, (_, i) => ({ companyId: fixture.companyId, clientId: fixture.site.clientId,
      agencyId: fixture.agency.id, label: `UIQA Legacy Site ${String(i).padStart(3, "0")}`, address1: "Fictional old address", updatedAt: new Date("2020-01-02") })) })
    const site = await db.customerSite.findFirstOrThrow({ where: { companyId: fixture.companyId, label: "UIQA Legacy Site 200" } })
    const equipment = await db.equipment.create({ data: { companyId: fixture.companyId, siteId: site.id, label: "UIQA Historical Equipment", status: "IMPORTED_CUSTOM_STATUS" } })
    const errors: string[] = []
    page.on("pageerror", error => errors.push(error.message))
    await page.context().clearCookies()
    await page.goto("/auth/login")
    await page.getByLabel("Adresse e-mail professionnelle").fill(fixture.user.email!)
    await page.getByLabel("Mot de passe", { exact: true }).fill(password)
    await page.getByRole("button", { name: "Se connecter", exact: true }).click()
    await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
    await page.goto("/dashboard/operations?tab=assets")
    const sites = page.getByRole("region", { name: "Sites clients", exact: true })
    const park = page.getByRole("region", { name: "Parc installé", exact: true })
    await sites.getByRole("textbox", { name: "Rechercher un site", exact: true }).fill(site.label)
    const siteRow = sites.getByRole("article", { name: site.label, exact: true })
    await siteRow.getByRole("button", { name: "Modifier", exact: true }).click()
    const edit = page.getByRole("dialog", { name: "Modifier le site", exact: true })
    await edit.getByLabel("Adresse", { exact: true }).fill("Fictional preserved address")
    await db.customerSite.update({ where: { id: site.id }, data: { address1: "Fictional concurrent address", updatedAt: new Date() } })
    await edit.getByRole("button", { name: "Enregistrer", exact: true }).click()
    await expect(edit.getByRole("alert")).toContainText("Ce site a changé")
    await expect(edit.getByLabel("Adresse", { exact: true })).toHaveValue("Fictional preserved address")
    await edit.getByRole("button", { name: "Annuler", exact: true }).click()
    await park.getByRole("textbox", { name: "Rechercher un équipement", exact: true }).fill(equipment.label)
    const equipmentRow = park.getByRole("article", { name: equipment.label, exact: true })
    await equipmentRow.getByRole("button", { name: "Désactiver", exact: true }).click()
    await page.getByRole("dialog").getByRole("button", { name: "Désactiver le référencement", exact: true }).click()
    await expect(equipmentRow.getByText("Référencement désactivé", { exact: true })).toBeVisible()
    await expect(equipmentRow.getByText("IMPORTED_CUSTOM_STATUS", { exact: true })).toBeVisible()
    await siteRow.getByRole("button", { name: "Désactiver", exact: true }).click()
    await page.getByRole("dialog").getByRole("button", { name: "Désactiver le référencement", exact: true }).click()
    await expect(siteRow.getByText("Référencement désactivé", { exact: true })).toBeVisible()
    await equipmentRow.getByRole("button", { name: "Réactiver", exact: true }).click()
    const activity = page.getByRole("dialog")
    await activity.getByRole("button", { name: "Réactiver le référencement", exact: true }).click()
    await expect(activity.getByRole("alert")).toContainText("Site client introuvable ou désactivé")
    await activity.getByRole("button", { name: "Annuler", exact: true }).click()
    await siteRow.getByRole("button", { name: "Réactiver", exact: true }).click()
    await page.getByRole("dialog").getByRole("button", { name: "Réactiver le référencement", exact: true }).click()
    await expect(siteRow.getByText("Référencement désactivé", { exact: true })).toHaveCount(0)

    await page.getByTestId("operation-composer").locator("summary").click()
    await page.getByRole("combobox", { name: "Type d’opération", exact: true }).click()
    await page.getByRole("option", { name: "Équipement", exact: true }).click()
    const composer = page.getByTestId("operation-composer")
    const siteChoice = composer.locator("select[name=siteId]").locator("..")
    await composer.getByRole("textbox", { name: "Rechercher un site à rattacher", exact: true }).fill(site.label)
    await expect(siteChoice.getByText("1 résultat", { exact: true })).toBeVisible()
    await composer.locator("select[name=siteId]").selectOption(site.id)
    await composer.getByRole("textbox", { name: "Rechercher un site à rattacher", exact: true }).fill("UIQA Legacy Site")
    await expect(siteChoice.getByText("201 résultats", { exact: true })).toBeVisible()
    await expect(composer.locator("select[name=siteId]")).toHaveValue(site.id)
    await composer.getByLabel(/^Équipement(?: \*)?$/).fill("UIQA Preserved Creation")
    await db.customerSite.update({ where: { id: site.id }, data: { archivedAt: new Date() } })
    await composer.getByRole("button", { name: "Enregistrer", exact: true }).click()
    await expect(page.getByText("Site client introuvable ou désactivé", { exact: true })).toBeVisible()
    await expect(composer.getByLabel(/^Équipement(?: \*)?$/)).toHaveValue("UIQA Preserved Creation")
    expect(await db.equipment.count({ where: { companyId: fixture.companyId, label: "UIQA Preserved Creation" } })).toBe(0)
    expect(errors).toEqual([])
  } finally {
    await db.auditLog.deleteMany({ where: { userId: fixture.user.id } })
    await fixture.cleanup()
    await db.$disconnect()
  }
})
