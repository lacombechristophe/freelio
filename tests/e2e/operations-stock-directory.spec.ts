import { PrismaClient } from "@prisma/client"
import { expect, test } from "@playwright/test"

const database = new PrismaClient()
test.afterAll(async () => { await database.$disconnect() })

test("complete stock keeps indicators, agency and open input through pagination and recovery", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette Stock exige une SQLite fictive isolée")
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message))
  const lastId = `copsstocklast${info.project.name}`
  const last = await database.product.findUniqueOrThrow({ where: { id: lastId } })
  const user = await database.user.findUniqueOrThrow({ where: { email: `operations-stock-${info.project.name}@example.test` }, select: { id: true } })
  const before = await database.inventoryItem.findMany({ where: { companyId: last.companyId }, orderBy: { id: "asc" } })
  await page.context().clearCookies(); await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(`operations-stock-${info.project.name}@example.test`)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto("/dashboard/operations?create=1")
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  const metric = page.locator(".workspace-metric").filter({ has: page.getByText("Stocks bas", { exact: true }) })
  await expect(metric.getByText("501", { exact: true })).toBeVisible()
  await expect(page.getByText("Disponibilité nette inférieure ou égale au seuil. 5 affichées sur 501.", { exact: true })).toBeVisible()
  const agencyCard = page.locator("article").filter({ has: page.getByText("Fictional stock agency", { exact: true }) })
  await expect(agencyCard).toContainText("10 unités")
  await expect(agencyCard).toContainText("94,68")
  const form = page.getByTestId("operation-composer").locator("form")
  await form.locator("#title").fill("Fictional stock input kept")
  await form.locator("#description").fill("Fictional description kept during stock reads")
  await page.getByRole("tab", { name: "Stock & achats", exact: true }).click()
  const directory = page.getByRole("region", { name: "Stock par produit", exact: true })
  const search = directory.getByRole("textbox", { name: "Rechercher dans le stock", exact: true })
  await expect(directory.getByText("501 résultats", { exact: true })).toBeVisible()
  await directory.getByRole("button", { name: "Page suivante", exact: true }).click()
  await expect(directory.getByText("Page 2 sur 21", { exact: true })).toBeVisible()
  await expect(metric.getByText("501", { exact: true })).toBeVisible()
  await search.fill("zz-last")
  await expect(directory.getByText("1 résultat", { exact: true })).toBeVisible()
  await expect(directory.getByText("ZZ DERNIER PRODUIT", { exact: true })).toBeVisible()
  await expect(directory.getByText("10 disponibles", { exact: true })).toBeVisible()
  await page.getByRole("combobox", { name: "Filtrer par agence", exact: true }).click()
  await page.getByRole("option", { name: "Fictional stock agency", exact: true }).click()
  await expect(directory.getByText("1 résultat", { exact: true })).toBeVisible()
  await expect(metric.getByText("1", { exact: true })).toBeVisible()
  await expect(search).toHaveValue("zz-last")
  await page.route("**/dashboard/operations?create=1", async route => {
    if (route.request().headers()["next-action"] && route.request().postData()?.includes("FAIL-STOCK-READ")) await route.fulfill({ status: 503, body: "Fictional stock read failure" })
    else await route.continue()
  })
  await search.fill("FAIL-STOCK-READ")
  await expect(directory.getByRole("alert")).toContainText("Impossible d’actualiser la liste.")
  await expect(search).toHaveValue("FAIL-STOCK-READ")
  await expect(page.getByRole("combobox", { name: "Filtrer par agence", exact: true })).toContainText("Fictional stock agency")
  await expect(form.locator("#title")).toHaveValue("Fictional stock input kept")
  await expect(form.locator("#description")).toHaveValue("Fictional description kept during stock reads")
  await expect(metric.getByText("1", { exact: true })).toBeVisible()
  await page.unroute("**/dashboard/operations?create=1")
  await directory.getByRole("button", { name: "Réessayer", exact: true }).click()
  await expect(directory.getByText("0 résultats", { exact: true })).toBeVisible()
  await search.fill("dernier")
  await expect(directory.getByText("1 résultat", { exact: true })).toBeVisible()
  await expect(directory.getByText("10 disponibles", { exact: true })).toBeVisible()
  await expect(form.locator("#title")).toHaveValue("Fictional stock input kept")
  expect(await database.inventoryItem.findMany({ where: { companyId: last.companyId }, orderBy: { id: "asc" } })).toEqual(before)
  expect(await database.stockMovement.count({ where: { companyId: last.companyId } })).toBe(0)
  expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(0)
  expect(await database.emailDelivery.count({ where: { companyId: last.companyId } })).toBe(0)
  expect(errors).toEqual([])
})
