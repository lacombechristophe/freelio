import { createDatabaseClient } from "@/lib/database-client"
import { expect, test } from "@playwright/test"

const database = createDatabaseClient()
test.afterAll(async () => { await database.$disconnect() })

test("purchase choices preserve independent lines, edited prices and recovery", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette Achat exige une SQLite fictive isolée")
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message))
  const surface = info.project.name, productId = `cpurchasechoicelastproduct${surface}`, projectId = `cpurchasechoicelastproject${surface}`
  const product = await database.product.findUniqueOrThrow({ where: { id: productId } })
  await page.context().clearCookies(); await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(`purchase-choices-${surface}@example.test`)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto("/dashboard/operations?tab=stock")
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  await page.getByRole("button", { name: "Nouvelle commande", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Nouvelle commande fournisseur", exact: true })
  const save = dialog.getByRole("button", { name: "Créer le brouillon", exact: true })
  const projectChoice = dialog.locator("#purchase-project").locator("..")
  const projectSearch = projectChoice.getByRole("textbox", { name: "Rechercher un chantier pour l’achat", exact: true })
  await expect(projectChoice.getByText("301 résultats", { exact: true })).toBeVisible()
  await projectChoice.getByRole("button", { name: "Page suivante", exact: true }).click()
  await expect(projectChoice.getByText("Page 2 sur 13", { exact: true })).toBeVisible()
  await projectSearch.fill("Chantier 000")
  await expect(projectChoice.getByText("1 résultat", { exact: true })).toBeVisible()
  await projectChoice.locator("select").selectOption(`cpurchasechoicefirstproject${surface}`)
  await database.project.delete({ where: { id: `cpurchasechoicefirstproject${surface}` } })
  await projectSearch.fill("dernier")
  await expect(projectChoice.getByRole("alert")).toContainText("Impossible d’actualiser la liste.")
  await expect(save).toBeDisabled()
  await projectChoice.locator("select").selectOption(projectId)
  await expect(projectChoice.getByRole("alert")).toBeHidden()
  await projectSearch.fill("ABSENT")
  await expect(projectChoice.getByText("0 résultats", { exact: true })).toBeVisible()
  await expect(projectChoice.locator("select")).toHaveValue(projectId)
  await dialog.getByLabel("Fournisseur de la commande", { exact: true }).selectOption(`cpurchasechoicesupplier${surface}`)
  await dialog.getByLabel("Livraison souhaitée", { exact: true }).fill("2030-01-02")
  await dialog.getByLabel("Instructions fournisseur", { exact: true }).fill("Fictional kept purchase instructions")
  let first = dialog.locator("[data-purchase-line]").nth(0)
  await expect(first.getByText("501 résultats", { exact: true })).toBeVisible()
  await first.getByRole("button", { name: "Page suivante", exact: true }).click()
  await expect(first.getByText("Page 2 sur 21", { exact: true })).toBeVisible()
  await first.getByRole("textbox", { name: "Rechercher une référence pour la ligne 1", exact: true }).fill("Produit 000")
  await expect(first.getByText("1 résultat", { exact: true })).toBeVisible()
  await first.getByLabel("Produit fournisseur 1", { exact: true }).selectOption(`cpurchasechoicefirstproduct${surface}`)
  await dialog.getByRole("button", { name: "Ajouter une ligne", exact: true }).click()
  const second = dialog.locator("[data-purchase-line]").nth(1)
  const secondSearch = second.getByRole("textbox", { name: "Rechercher une référence pour la ligne 2", exact: true })
  await secondSearch.fill("zz-last")
  await expect(second.getByText("1 résultat", { exact: true })).toBeVisible()
  await second.getByLabel("Produit fournisseur 2", { exact: true }).selectOption(productId)
  await expect(second.getByLabel("Prix fournisseur 2", { exact: true })).toHaveValue("7.89")
  await second.getByLabel("Prix fournisseur 2", { exact: true }).fill("12.34")
  await second.getByLabel("Quantité fournisseur 2", { exact: true }).fill("2")
  await second.getByLabel("Libellé fournisseur 2", { exact: true }).fill("Fictional kept second purchase line")
  await database.product.update({ where: { id: productId }, data: { purchasePriceCents: 999 } })
  await page.route("**/dashboard/operations?tab=stock", async route => {
    if (route.request().headers()["next-action"] && route.request().postData()?.includes("FAIL-PURCHASE-CHOICE")) await route.fulfill({ status: 503, body: "Fictional purchase choice failure" })
    else await route.continue()
  })
  await secondSearch.fill("FAIL-PURCHASE-CHOICE")
  await expect(second.getByRole("alert")).toContainText("Impossible d’actualiser la liste.")
  await expect(save).toBeDisabled()
  await expect(second.getByLabel("Produit fournisseur 2", { exact: true })).toHaveValue(productId)
  await expect(second.getByLabel("Prix fournisseur 2", { exact: true })).toHaveValue("12.34")
  await page.unroute("**/dashboard/operations?tab=stock")
  await second.getByRole("button", { name: "Réessayer", exact: true }).click()
  await expect(second.getByText("0 résultats", { exact: true })).toBeVisible()
  await expect(secondSearch).toHaveValue("FAIL-PURCHASE-CHOICE")
  await database.product.delete({ where: { id: `cpurchasechoicefirstproduct${surface}` } })
  await first.getByRole("textbox", { name: "Rechercher une référence pour la ligne 1", exact: true }).fill("dernier")
  await expect(first.getByRole("alert")).toContainText("Impossible d’actualiser la liste.")
  await expect(save).toBeDisabled()
  await first.getByLabel("Produit fournisseur 1", { exact: true }).selectOption(productId)
  await expect(first.getByRole("alert")).toBeHidden()
  await first.getByRole("button", { name: "Supprimer la ligne fournisseur 1", exact: true }).click()
  first = dialog.locator("[data-purchase-line]").nth(0)
  await expect(first.getByLabel("Produit fournisseur 1", { exact: true })).toHaveValue(productId)
  await expect(first.getByRole("textbox", { name: "Rechercher une référence pour la ligne 1", exact: true })).toHaveValue("FAIL-PURCHASE-CHOICE")
  await expect(first.getByLabel("Prix fournisseur 1", { exact: true })).toHaveValue("12.34")
  await expect(first.getByLabel("Quantité fournisseur 1", { exact: true })).toHaveValue("2")
  await expect(first.getByLabel("Libellé fournisseur 1", { exact: true })).toHaveValue("Fictional kept second purchase line")
  await dialog.getByRole("button", { name: "Ajouter une ligne", exact: true }).click()
  const free = dialog.locator("[data-purchase-line]").nth(1)
  await free.getByLabel("Libellé fournisseur 2", { exact: true }).fill("Fictional free purchase line")
  await free.getByLabel("Prix fournisseur 2", { exact: true }).fill("3")
  await expect(projectChoice.locator("select")).toHaveValue(projectId)
  await expect(dialog.getByLabel("Fournisseur de la commande", { exact: true })).toHaveValue(`cpurchasechoicesupplier${surface}`)
  await expect(dialog.getByLabel("Livraison souhaitée", { exact: true })).toHaveValue("2030-01-02")
  await expect(dialog.getByLabel("Instructions fournisseur", { exact: true })).toHaveValue("Fictional kept purchase instructions")
  await expect(save).toBeEnabled(); await save.click()
  await expect(dialog).toBeHidden()
  const order = await database.purchaseOrder.findFirstOrThrow({ where: { companyId: product.companyId }, include: { lines: { orderBy: { order: "asc" } } } })
  expect(order).toMatchObject({ projectId, supplierId: `cpurchasechoicesupplier${surface}`, status: "DRAFT", totalHtCents: 2768, notes: "Fictional kept purchase instructions", lines: [{ productId, label: "Fictional kept second purchase line", quantity: 2, unitPriceCents: 1234 }, { productId: null, label: "Fictional free purchase line", quantity: 1, unitPriceCents: 300 }] })
  expect(await database.stockMovement.count({ where: { companyId: product.companyId } })).toBe(0)
  expect(await database.emailDelivery.count({ where: { companyId: product.companyId } })).toBe(0)
  expect(errors).toEqual([])
})
