import { expect, test } from "@playwright/test"

test("distinguishes recorded provider observations from local CRM state and reports a disconnected attachment read", async ({ page }) => {
  await page.goto("/dashboard/communications?tab=inbox")
  await page.getByLabel("Recherche", { exact: true }).fill("UIQA Remote observation")
  await page.getByRole("button", { name: "Rechercher", exact: true }).click()
  await page.locator("button[data-selected]").filter({ hasText: "UIQA Remote observation" }).click()
  await expect(page.getByText("Clos", { exact: true })).toBeVisible()
  await expect(page.getByText(/La lecture et la clôture dans Freelio modifient le suivi CRM/)).toBeVisible()
  const observed = page.locator("article").filter({ has: page.getByText("UIQA Remote observed", { exact: true }) })
  await expect(observed.getByText(/Non lu chez le fournisseur · Réception/)).toBeVisible()
  await expect(observed.getByText(/aucune archive locale durable/)).toBeVisible()
  await expect(observed.getByText("Type de pièce non pris en charge", { exact: true })).toBeVisible()
  const missing = page.locator("article").filter({ has: page.getByText("UIQA Remote missing", { exact: true }) })
  await expect(missing.getByText(/Message absent chez le fournisseur — copie CRM conservée/)).toBeVisible()
  await expect(missing.getByRole("button", { name: "Télécharger", exact: true })).toHaveCount(0)
  await expect(page.getByText("État fournisseur non observé.", { exact: true })).toBeVisible()
  await expect(page.getByText("hidden-remote@example.test", { exact: true })).toHaveCount(0)
  const response = page.waitForResponse(response => response.url().includes("/api/communications/messages/") && response.url().includes("/attachments/"))
  await observed.getByRole("button", { name: "Télécharger", exact: true }).click()
  expect((await response).status()).toBe(502)
  await expect(observed.getByRole("alert")).toContainText("Pièce indisponible ; vérifiez la connexion de la messagerie")
  await expect(observed.getByText("Fictional retained copy 0", { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(await page.evaluate(() => window.innerWidth))
})
