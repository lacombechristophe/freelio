import { createDatabaseClient } from "@/lib/database-client"
import { randomUUID } from "node:crypto"
import { expect, test } from "@playwright/test"

const database = createDatabaseClient()
test.afterAll(async () => { await database.$disconnect() })

test("project workspace keeps saved state and preserves drafts after stale revisions", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette Espace Chantier exige une SQLite fictive isolée")
  const source = await database.user.findUniqueOrThrow({ where: { email: `purchase-creation-${info.project.name}@example.test` }, select: { passwordHash: true } })
  const company = await database.company.create({ data: { name: "Fictitious workspace browser company" } })
  await database.saasSubscription.create({ data: { companyId: company.id, plan: "RESEAU", status: "ACTIVE", seatQuantity: 10 } })
  const email = `workspace-${info.project.name}-${randomUUID()}@example.test`
  const user = await database.user.create({ data: { companyId: company.id, email, emailVerified: new Date(), passwordHash: source.passwordHash } })
  await database.membership.create({ data: { companyId: company.id, userId: user.id, role: "OWNER", status: "ACTIVE" } })
  const client = await database.client.create({ data: { companyId: company.id, name: "Fictitious workspace client" } })
  const project = await database.project.create({ data: { companyId: company.id, clientId: client.id, name: "Fictitious workspace browser project" } })
  const milestone = await database.projectMilestone.create({ data: { projectId: project.id, title: "Fictitious planned milestone", dueDate: new Date("2030-02-21T12:00:00Z") } })
  const profile = await database.projectTechnicalProfile.create({ data: { projectId: project.id, surveyStatus: "SURVEYED", poolLengthMm: 8000 } })
  const foreignCompany = await database.company.create({ data: { name: "Fictitious foreign workspace" } })
  const foreignUser = await database.user.create({ data: { email: `foreign-${randomUUID()}@example.test`, name: "FOREIGN-WORKSPACE-MEMBER-SECRET" } })
  const foreignMember = await database.membership.create({ data: { companyId: foreignCompany.id, userId: foreignUser.id, role: "OWNER", status: "ACTIVE" } })
  const foreignClient = await database.client.create({ data: { companyId: foreignCompany.id, name: "Fictitious foreign workspace client" } })
  const foreignProject = await database.project.create({ data: { companyId: foreignCompany.id, clientId: foreignClient.id, name: "Fictitious foreign project" } })
  const foreignDependency = await database.projectMilestone.create({ data: { projectId: foreignProject.id, title: "FOREIGN-WORKSPACE-DEPENDENCY-SECRET" } })
  await database.projectMilestone.create({ data: { projectId: project.id, title: "Fictitious unavailable references", dependsOnId: foreignDependency.id, assignedMembershipId: foreignMember.id, order: 1 } })
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  await page.context().clearCookies()
  await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(email)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto(`/dashboard/projets/${project.id}`)
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  const unavailable = page.locator("div.rounded-lg.border.p-3").filter({ has: page.getByText("Fictitious unavailable references", { exact: true }) })
  await expect(unavailable).toContainText("Dépendance indisponible")
  await expect(unavailable).toContainText("Responsable indisponible")
  await expect(unavailable.getByTitle("Planifier", { exact: true })).toBeDisabled()
  await expect(unavailable.getByTitle("Supprimer", { exact: true })).toBeDisabled()
  await expect(page.locator("body")).not.toContainText("FOREIGN-WORKSPACE-DEPENDENCY-SECRET")
  await expect(page.locator("body")).not.toContainText("FOREIGN-WORKSPACE-MEMBER-SECRET")

  const summary = page.locator('[data-slot="card"]').filter({ has: page.getByText("Relevé technique bassin & pose", { exact: true }) })
  await summary.getByRole("button", { name: "Modifier", exact: true }).click()
  const editor = page.getByRole("dialog", { name: "Relevé technique bassin & pose", exact: true })
  await editor.getByLabel("État du relevé", { exact: true }).selectOption("VALIDATED")
  await editor.getByLabel("Longueur", { exact: true }).fill("8200")
  await expect(summary).toContainText("Relevé effectué")
  await expect(summary).toContainText("8000 mm")
  const concurrent = await database.projectTechnicalProfile.update({ where: { projectId: project.id }, data: { poolLengthMm: 9000, updatedAt: new Date(profile.updatedAt.getTime() + 1000) } })
  await editor.getByRole("button", { name: "Enregistrer le relevé", exact: true }).click()
  await expect(page.getByText("Le chantier a changé. Rechargez la page puis réessayez ; votre saisie est conservée.", { exact: true })).toBeVisible()
  await expect(editor).toBeVisible()
  await expect(editor.getByLabel("Longueur", { exact: true })).toHaveValue("8200")
  await expect(editor.getByLabel("État du relevé", { exact: true })).toHaveValue("VALIDATED")
  expect(await database.projectTechnicalProfile.findUniqueOrThrow({ where: { projectId: project.id } })).toEqual(concurrent)
  await editor.getByRole("button", { name: "Annuler", exact: true }).click()
  await page.reload()
  await summary.getByRole("button", { name: "Modifier", exact: true }).click()
  await expect(editor.getByLabel("Longueur", { exact: true })).toHaveValue("9000")
  await editor.getByLabel("Longueur", { exact: true }).fill("9200")
  await editor.getByLabel("État du relevé", { exact: true }).selectOption("VALIDATED")
  await editor.getByRole("button", { name: "Enregistrer le relevé", exact: true }).click()
  await expect(editor).toBeHidden()
  await expect(summary).toContainText("9200 mm")
  await expect(summary).toContainText("Relevé validé pour préparation et pose.")

  const row = page.locator("div.rounded-lg.border.p-3").filter({ has: page.getByText(milestone.title, { exact: true }) })
  await row.getByTitle("Planifier", { exact: true }).click()
  const planner = page.getByRole("dialog", { name: `Planifier ${milestone.title}`, exact: true })
  await planner.getByLabel("Échéance", { exact: true }).fill("2030-02-23")
  await planner.getByLabel("Durée (jours)", { exact: true }).fill("3")
  const changed = await database.projectMilestone.update({ where: { id: milestone.id }, data: { dueDate: new Date("2030-02-24T12:00:00Z"), updatedAt: new Date(milestone.updatedAt.getTime() + 1000) } })
  await planner.getByRole("button", { name: "Enregistrer", exact: true }).click()
  await expect(page.getByText("Le chantier a changé. Rechargez la page puis réessayez ; votre saisie est conservée.", { exact: true })).toBeVisible()
  await expect(planner).toBeVisible()
  await expect(planner.getByLabel("Échéance", { exact: true })).toHaveValue("2030-02-23")
  await expect(planner.getByLabel("Durée (jours)", { exact: true })).toHaveValue("3")
  expect(await database.projectMilestone.findUniqueOrThrow({ where: { id: milestone.id } })).toEqual(changed)
  expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(1)
  expect(errors).toEqual([])
})
