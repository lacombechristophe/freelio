import { randomUUID } from "node:crypto"
import { PrismaClient } from "@prisma/client"
import { expect, test } from "@playwright/test"

const database = new PrismaClient()
test.afterAll(async () => { await database.$disconnect() })

test("delivery choices preserve input and verify order-scoped selections", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette Choix Livraison exige une SQLite fictive isolée")
  const source = await database.user.findUniqueOrThrow({ where: { email: `purchase-creation-${info.project.name}@example.test` }, select: { passwordHash: true } })
  const company = await database.company.create({ data: { name: "Fictional delivery choice company" } })
  await database.saasSubscription.create({ data: { companyId: company.id, plan: "RESEAU", status: "ACTIVE", seatQuantity: 10 } })
  const email = `delivery-choices-${info.project.name}-${randomUUID()}@example.test`
  const user = await database.user.create({ data: { companyId: company.id, email, emailVerified: new Date(), passwordHash: source.passwordHash } })
  await database.membership.create({ data: { companyId: company.id, userId: user.id, role: "OWNER", status: "ACTIVE" } })
  const client = await database.client.create({ data: { companyId: company.id, name: "Fictional choice client" } })
  const project = await database.project.create({ data: { companyId: company.id, clientId: client.id, name: "Fictional choice project" } })
  await database.customerOrder.createMany({ data: Array.from({ length: 151 }, (_, index) => ({ companyId: company.id, clientId: client.id, projectId: project.id, number: `CHOICE-${String(index).padStart(3, "0")}`, status: "CONFIRMED", createdAt: new Date(Date.UTC(2000, 0, 1, 0, index)) })) })
  const orders = await database.customerOrder.findMany({ where: { companyId: company.id }, select: { id: true, number: true } })
  const oldest = orders.find(item => item.number === "CHOICE-000")!, other = orders.find(item => item.number === "CHOICE-001")!
  await database.customerOrderLine.createMany({ data: orders.map(order => ({ customerOrderId: order.id, label: "Original choice material", quantity: 3, deliveredQuantity: 1, unitPriceCents: 100 })) })
  const baseLine = await database.customerOrderLine.findFirstOrThrow({ where: { customerOrderId: oldest.id, order: 0 } })
  const otherLine = await database.customerOrderLine.findFirstOrThrow({ where: { customerOrderId: other.id } })
  await database.customerOrderLine.createMany({ data: Array.from({ length: 150 }, (_, index) => ({ customerOrderId: oldest.id, label: `Material ${String(index).padStart(3, "0")}`, order: index + 1, quantity: 0.3, deliveredQuantity: 0.1, unitPriceCents: 100 })) })
  const lastLine = await database.customerOrderLine.findFirstOrThrow({ where: { customerOrderId: oldest.id, order: 150 } })
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message))
  await page.context().clearCookies(); await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(email)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto("/dashboard/operations?tab=orders&create=1")
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  const composer = page.getByTestId("operation-composer")
  await composer.getByRole("combobox", { name: "Type d’opération", exact: true }).click()
  await page.getByRole("option", { name: "Bon de livraison", exact: true }).click()
  const form = composer.locator("form"), orderSelect = form.locator("#customerOrderId"), lineSelect = form.locator("#customerOrderLineId")
  const orderField = orderSelect.locator(".."), lineField = lineSelect.locator("..")
  const orderSearch = form.getByRole("textbox", { name: "Rechercher une commande à livrer", exact: true })
  const lineSearch = form.getByRole("textbox", { name: "Rechercher une ligne à livrer", exact: true })
  const save = form.getByRole("button", { name: "Enregistrer", exact: true })
  await form.locator("#quantity").fill("0.0001")
  await form.locator("#recipientName").fill("Preserved fictional recipient")
  await expect(save).toBeDisabled()
  await expect(orderField.getByRole("status")).toHaveText("151 résultats")
  for (let index = 0; index < 6; index++) {
    await orderField.getByRole("button", { name: "Page suivante", exact: true }).click()
    await expect(orderField.getByText(`Page ${index + 2} sur 7`, { exact: true })).toBeVisible()
    await expect(orderField.getByRole("status")).toHaveText("151 résultats")
  }
  await orderSelect.selectOption(oldest.id)
  await expect(lineField.getByRole("status")).toHaveText("151 résultats")
  for (let index = 0; index < 6; index++) {
    await lineField.getByRole("button", { name: "Page suivante", exact: true }).click()
    await expect(lineField.getByText(`Page ${index + 2} sur 7`, { exact: true })).toBeVisible()
    await expect(lineField.getByRole("status")).toHaveText("151 résultats")
  }
  await lineSelect.selectOption(lastLine.id)
  await expect(save).toBeEnabled()
  await expect(lineSelect.locator("option:checked")).toHaveText("Material 149 · reste 0,2")
  await orderSearch.fill("no matching order")
  await expect(orderField.getByRole("status")).toHaveText("0 résultats")
  await lineSearch.fill("no matching line")
  await expect(lineField.getByRole("status")).toHaveText("0 résultats")
  await expect(orderSelect).toHaveValue(oldest.id)
  await expect(lineSelect).toHaveValue(lastLine.id)
  await expect(save).toBeEnabled()
  await page.route("**/dashboard/operations*", route => route.request().method() === "POST" ? route.abort("failed") : route.continue())
  await lineSearch.fill("network failure probe")
  await expect(lineField.getByRole("alert")).toContainText("Impossible d’actualiser la liste.")
  await expect(save).toBeDisabled()
  await expect(form.locator("#quantity")).toHaveValue("0.0001")
  await expect(form.locator("#recipientName")).toHaveValue("Preserved fictional recipient")
  await page.unroute("**/dashboard/operations*")
  await lineField.getByRole("button", { name: "Réessayer", exact: true }).click()
  await expect(save).toBeEnabled()
  await orderSearch.fill("CHOICE-001")
  await expect(orderField.getByRole("status")).toHaveText("1 résultat")
  await orderSelect.selectOption(other.id)
  await expect(lineSelect).toHaveValue("")
  await expect(lineField.getByRole("status")).toHaveText("1 résultat")
  await expect(lineSelect.locator(`option[value="${lastLine.id}"]`)).toHaveCount(0)
  await expect(save).toBeDisabled()
  await lineSelect.selectOption(otherLine.id)
  await expect(save).toBeEnabled()
  await database.customerOrder.update({ where: { id: other.id }, data: { status: "CANCELED" } })
  await orderSearch.fill("CHOICE-000")
  await expect(orderField.getByRole("status")).toHaveText("1 résultat")
  await expect(orderField.getByRole("alert")).toContainText("La sélection n’est plus disponible.")
  await expect(save).toBeDisabled()
  await expect(form.locator("#quantity")).toHaveValue("0.0001")
  await expect(form.locator("#recipientName")).toHaveValue("Preserved fictional recipient")
  await orderSelect.selectOption(oldest.id)
  await expect(lineField.getByRole("status")).toHaveText("151 résultats")
  await lineSelect.selectOption(baseLine.id)
  await expect(save).toBeEnabled()
  await save.click()
  await expect(page.getByText("Bon de livraison enregistré.", { exact: true })).toBeVisible()
  const note = await database.deliveryNote.findFirstOrThrow({ where: { companyId: company.id }, include: { lines: true } })
  expect(note).toMatchObject({ customerOrderId: oldest.id, recipientName: "Preserved fictional recipient", lines: [{ customerOrderLineId: baseLine.id, quantity: 0.0001 }] })
  expect((await database.customerOrderLine.findUniqueOrThrow({ where: { id: baseLine.id } })).deliveredQuantity).toBe(1.0001)
  expect((await database.customerOrder.findUniqueOrThrow({ where: { id: other.id } })).status).toBe("CANCELED")
  expect(await database.auditLog.count({ where: { userId: user.id, action: "CREATE_DELIVERY_NOTE" } })).toBe(1)
  expect(await database.emailDelivery.count({ where: { companyId: company.id } })).toBe(0)
  expect(errors).toEqual([])
})
