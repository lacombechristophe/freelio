import { randomUUID } from "node:crypto"
import { PrismaClient } from "@prisma/client"
import { expect, test } from "@playwright/test"

const database = new PrismaClient()
test.afterAll(async () => { await database.$disconnect() })

test("stock reservations retain balances and audits after a failed consumption", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette Réservation Stock exige une SQLite fictive isolée")
  const source = await database.user.findUniqueOrThrow({ where: { email: `purchase-creation-${info.project.name}@example.test` }, select: { passwordHash: true } })
  const company = await database.company.create({ data: { name: "Fictional reservation integrity company" } })
  await database.saasSubscription.create({ data: { companyId: company.id, plan: "RESEAU", status: "ACTIVE", seatQuantity: 10 } })
  const email = `stock-integrity-${info.project.name}-${randomUUID()}@example.test`
  const user = await database.user.create({ data: { companyId: company.id, email, emailVerified: new Date(), passwordHash: source.passwordHash } })
  await database.membership.create({ data: { companyId: company.id, userId: user.id, role: "OWNER", status: "ACTIVE" } })
  const client = await database.client.create({ data: { companyId: company.id, name: "Fictional stock client" } })
  const project = await database.project.create({ data: { companyId: company.id, clientId: client.id, name: "Fictional stock project" } })
  const order = await database.customerOrder.create({ data: { companyId: company.id, clientId: client.id, projectId: project.id, number: "STOCK-INTEGRITY", status: "CONFIRMED" } })
  const product = await database.product.create({ data: { companyId: company.id, sku: "STOCK-INTEGRITY", label: "Fictional stock integrity material" } })
  const warehouse = await database.warehouse.create({ data: { companyId: company.id, name: "Fictional stock warehouse", code: "STOCK-INTEGRITY" } })
  await database.inventoryItem.create({ data: { companyId: company.id, warehouseId: warehouse.id, productId: product.id, quantity: 10 } })
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message))
  await page.context().clearCookies(); await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(email)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto("/dashboard/operations?tab=orders&create=1")
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  const composer = page.getByTestId("operation-composer")
  await composer.getByRole("combobox", { name: "Type d’opération", exact: true }).click()
  await page.getByRole("option", { name: "Réservation de stock", exact: true }).click()
  const form = composer.locator("form"), directory = page.getByRole("region", { name: "Réservations actives", exact: true })
  async function reserve() {
    await form.locator("#warehouseId").selectOption(warehouse.id)
    await form.locator("#productId").selectOption(product.id)
    await form.locator("#customerOrderId").selectOption(order.id)
    await form.locator("#quantity").fill("6")
    await form.getByRole("button", { name: "Enregistrer", exact: true }).click()
    await expect(directory.getByRole("button", { name: "Libérer", exact: true })).toBeVisible()
  }
  await reserve()
  const first = await database.stockReservation.findFirstOrThrow({ where: { companyId: company.id, status: "ACTIVE" } })
  await directory.getByRole("button", { name: "Libérer", exact: true }).click()
  await expect.poll(async () => (await database.stockReservation.findUniqueOrThrow({ where: { id: first.id } })).status).toBe("RELEASED")
  await expect(directory.getByRole("button", { name: "Libérer", exact: true })).toHaveCount(0)
  await reserve()
  const second = await database.stockReservation.findFirstOrThrow({ where: { companyId: company.id, status: "ACTIVE" } })
  const consume = directory.getByRole("button", { name: "Consommer", exact: true })
  await database.$executeRawUnsafe(`CREATE TRIGGER "fictional_reservation_ui_audit" BEFORE INSERT ON "AuditLog" WHEN NEW."userId" = '${user.id}' AND NEW."action" = 'CONSUME_STOCK_RESERVATION' BEGIN SELECT RAISE(ABORT, 'Fictional UI audit failure'); END`)
  try {
    const response = page.waitForResponse(item => item.request().method() === "POST" && Boolean(item.request().postData()?.includes(second.id)))
    await consume.click(); await response
    await expect(consume).toBeEnabled()
    expect(await database.inventoryItem.findUniqueOrThrow({ where: { warehouseId_productId: { warehouseId: warehouse.id, productId: product.id } } })).toMatchObject({ quantity: 10, reservedQuantity: 6 })
    expect((await database.stockReservation.findUniqueOrThrow({ where: { id: second.id } })).status).toBe("ACTIVE")
    expect(await database.stockMovement.count({ where: { companyId: company.id } })).toBe(3)
    expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(3)
    expect((await database.customerOrder.findUniqueOrThrow({ where: { id: order.id } })).status).toBe("CONFIRMED")
  } finally { await database.$executeRawUnsafe('DROP TRIGGER IF EXISTS "fictional_reservation_ui_audit"') }
  await consume.click()
  await expect.poll(async () => (await database.stockReservation.findUniqueOrThrow({ where: { id: second.id } })).status).toBe("CONSUMED")
  expect(await database.inventoryItem.findUniqueOrThrow({ where: { warehouseId_productId: { warehouseId: warehouse.id, productId: product.id } } })).toMatchObject({ quantity: 4, reservedQuantity: 0 })
  expect(await database.stockMovement.count({ where: { companyId: company.id } })).toBe(4)
  expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(4)
  expect((await database.customerOrder.findUniqueOrThrow({ where: { id: order.id } })).status).toBe("IN_PREPARATION")
  expect(await database.emailDelivery.count({ where: { companyId: company.id } })).toBe(0)
  expect(errors).toEqual([])
})
