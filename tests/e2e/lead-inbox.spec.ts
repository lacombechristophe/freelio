import { createDatabaseClient } from "@/lib/database-client"
import { expect, test } from "@playwright/test"

const database = createDatabaseClient()
test.afterAll(async () => { await database.$disconnect() })
test("Incoming inbox searches its complete portfolio and preserves filters through failure and a status change", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette Prospects exige une SQLite fictive isolée")
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  const oldestId = `cleadinboxoldest${info.project.name}`
  const oldest = await database.leadCapture.findUniqueOrThrow({ where: { id: oldestId } })
  await page.context().clearCookies(); await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(`lead-inbox-${info.project.name}@example.test`)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto("/dashboard/leads")
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  const metrics = page.getByRole("region", { name: "Indicateurs des prospects", exact: true })
  const metric = (label: string) => metrics.getByText(label, { exact: true }).locator("..")
  await expect(page.getByText("151 résultats", { exact: true })).toBeVisible()
  await expect(metric("À traiter").getByText("151", { exact: true })).toBeVisible()
  await expect(metric("Consentements").getByText("1", { exact: true })).toBeVisible()
  for (let pageNumber = 2; pageNumber <= 7; pageNumber++) {
    await page.getByRole("button", { name: "Page suivante", exact: true }).click()
    await expect(page.getByText(`Page ${pageNumber} sur 7`, { exact: true })).toBeVisible()
    await expect(page.getByRole("button", { name: "Page précédente", exact: true })).toBeEnabled()
  }
  const records = info.project.name === "mobile" ? page.locator("article") : page.getByRole("row")
  await expect(records.getByText("OLDEST-INBOX-LEAD Portfolio", { exact: true })).toBeVisible()
  const search = page.getByRole("textbox", { name: "Rechercher un prospect", exact: true })
  const filter = page.getByRole("combobox", { name: "Filtrer les prospects", exact: true })
  await search.fill("OLDEST-INBOX-LEAD")
  await expect(page.getByText("1 résultat", { exact: true })).toBeVisible()
  await expect(page.getByText("Page 1 sur 1", { exact: true })).toBeVisible()
  await filter.click(); await page.getByRole("option", { name: "Nouveau", exact: true }).click()
  await expect(page.getByText("1 résultat", { exact: true })).toBeVisible()
  await page.route("**/dashboard/leads", async route => {
    if (route.request().headers()["next-action"] && route.request().postData()?.includes("FAIL-INBOX")) await route.fulfill({ status: 503, body: "Fictional inbox lookup failure" })
    else await route.continue()
  })
  await search.fill("FAIL-INBOX")
  await expect(page.getByRole("alert").filter({ hasText: "Impossible d’actualiser la liste." })).toBeVisible()
  await expect(search).toHaveValue("FAIL-INBOX"); await expect(filter).toContainText("Nouveau")
  await expect(page.getByRole("combobox", { name: "Statut de OLDEST-INBOX-LEAD Portfolio", exact: true })).toBeDisabled()
  await expect(metric("Consentements").getByText("1", { exact: true })).toBeVisible()
  await page.unroute("**/dashboard/leads")
  await page.getByRole("button", { name: "Réessayer", exact: true }).click()
  await expect(page.getByText("0 résultats", { exact: true })).toBeVisible()
  await expect(search).toHaveValue("FAIL-INBOX"); await expect(filter).toContainText("Nouveau")
  await search.fill("OLDEST-INBOX-LEAD")
  await expect(page.getByText("1 résultat", { exact: true })).toBeVisible()
  const status = page.getByRole("combobox", { name: "Statut de OLDEST-INBOX-LEAD Portfolio", exact: true })
  await expect(status).toBeEnabled(); await status.click()
  await page.getByRole("option", { name: "Contacté", exact: true }).click()
  await expect(page.getByText("0 résultats", { exact: true })).toBeVisible()
  await expect(search).toHaveValue("OLDEST-INBOX-LEAD"); await expect(filter).toContainText("Nouveau")
  await expect(metric("À traiter").getByText("150", { exact: true })).toBeVisible()
  await expect(metric("Contactés").getByText("1", { exact: true })).toBeVisible()
  await filter.click(); await page.getByRole("option", { name: "Tous les statuts", exact: true }).click()
  await expect(page.getByText("1 résultat", { exact: true })).toBeVisible()
  await expect(status).toContainText("Contacté")
  expect((await database.leadCapture.findUniqueOrThrow({ where: { id: oldestId } })).status).toBe("CONTACTED")
  expect(await database.leadCapture.count({ where: { companyId: oldest.companyId } })).toBe(151)
  expect(await database.marketingConsent.count({ where: { companyId: oldest.companyId } })).toBe(0)
  expect(await database.emailDelivery.count({ where: { companyId: oldest.companyId } })).toBe(0)
  expect(await page.locator("body").innerText()).not.toContain("FOREIGN-INBOX-MARKER")
  expect(errors).toEqual([])
})
