import { randomUUID } from "node:crypto"
import { PrismaClient } from "@prisma/client"
import { expect, test } from "@playwright/test"

const database = new PrismaClient()
test.afterAll(async () => { await database.$disconnect() })

test("reservation references preserve input through pagination, failure and revoked selection", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette Références Réservation exige une SQLite fictive isolée")
  const source = await database.user.findUniqueOrThrow({ where: { email: `purchase-creation-${info.project.name}@example.test` }, select: { passwordHash: true } })
  const company = await database.company.create({ data: { name: "Fictitious reservation reference company" } })
  await database.saasSubscription.create({ data: { companyId: company.id, plan: "RESEAU", status: "ACTIVE", seatQuantity: 10 } })
  const email = `reservation-refs-${info.project.name}-${randomUUID()}@example.test`
  const user = await database.user.create({ data: { companyId: company.id, email, emailVerified: new Date(), passwordHash: source.passwordHash } })
  await database.membership.create({ data: { companyId: company.id, userId: user.id, role: "OWNER", status: "ACTIVE" } })
  const client = await database.client.create({ data: { companyId: company.id, name: "Fictitious reservation client" } })
  await database.project.createMany({ data: Array.from({ length: 301 }, (_, index) => ({ companyId: company.id, clientId: client.id, name: `Project ${String(index).padStart(3, "0")}` })) })
  const project = await database.project.findFirstOrThrow({ where: { companyId: company.id, name: "Project 300" } })
  await database.customerOrder.createMany({ data: Array.from({ length: 151 }, (_, index) => ({ companyId: company.id, clientId: client.id, projectId: project.id, number: `REF-${String(index).padStart(3, "0")}`, status: "CONFIRMED", createdAt: new Date(Date.UTC(2000, 0, 1, 0, index)) })) })
  const order = await database.customerOrder.findFirstOrThrow({ where: { companyId: company.id, number: "REF-000" } })
  const replacement = await database.customerOrder.findFirstOrThrow({ where: { companyId: company.id, number: "REF-001" } })
  const warehouse = await database.warehouse.create({ data: { companyId: company.id, name: "Fictitious reference warehouse", code: "REF-WH" } })
  const product = await database.product.create({ data: { companyId: company.id, sku: "REF-MATERIAL", label: "Fictitious reservation material", stockTracked: true } })
  await database.inventoryItem.create({ data: { companyId: company.id, warehouseId: warehouse.id, productId: product.id, quantity: 10 } })
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message))
  await page.context().clearCookies(); await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(email)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto("/dashboard/operations?tab=orders&create=1")
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  const composer = page.getByTestId("operation-composer")
  await composer.getByRole("combobox", { name: "Type d’opération", exact: true }).click()
  await page.getByRole("option", { name: "Réservation de stock", exact: true }).click()
  const form = composer.locator("form"), orderSelect = form.locator("#customerOrderId"), projectSelect = form.locator("#projectId")
  const orderField = orderSelect.locator(".."), projectField = projectSelect.locator("..")
  const orderSearch = form.getByRole("textbox", { name: "Rechercher une commande client", exact: true })
  const projectSearch = form.getByRole("textbox", { name: "Rechercher un chantier", exact: true })
  const save = form.getByRole("button", { name: "Enregistrer", exact: true })
  await expect(save).toBeDisabled()
  await form.locator("#warehouseId").selectOption(warehouse.id)
  await form.getByRole("textbox", { name: "Rechercher un produit", exact: true }).fill(product.sku)
  await expect(form.locator("#productId option").filter({ hasText: product.sku })).toHaveCount(1)
  await form.locator("#productId").selectOption(product.id)
  await form.locator("#quantity").fill("2")
  await expect(orderField.getByRole("status")).toHaveText("151 résultats")
  await expect(projectField.getByRole("status")).toHaveText("301 résultats")
  for (let index = 0; index < 6; index++) {
    await orderField.getByRole("button", { name: "Page suivante", exact: true }).click()
    await expect(orderField.getByText(`Page ${index + 2} sur 7`, { exact: true })).toBeVisible()
    await expect(orderField.getByRole("status")).toHaveText("151 résultats")
  }
  await orderSelect.selectOption(order.id)
  await projectSearch.fill("Project 300")
  await expect(projectField.getByRole("status")).toHaveText("1 résultat")
  await projectSelect.selectOption(project.id)
  await expect(save).toBeEnabled()
  await orderSearch.fill("no matching order")
  await projectSearch.fill("no matching project")
  await expect(orderField.getByRole("status")).toHaveText("0 résultats")
  await expect(projectField.getByRole("status")).toHaveText("0 résultats")
  await expect(orderSelect).toHaveValue(order.id); await expect(projectSelect).toHaveValue(project.id)
  await expect(save).toBeEnabled()
  await page.route("**/dashboard/operations*", route => route.request().method() === "POST" ? route.abort("failed") : route.continue())
  await projectSearch.fill("network failure probe")
  await expect(projectField.getByRole("alert").filter({ hasText: "Impossible d’actualiser la liste." })).toBeVisible()
  await expect(save).toBeDisabled()
  await expect(form.locator("#quantity")).toHaveValue("2")
  await expect(form.locator("#warehouseId")).toHaveValue(warehouse.id)
  await expect(form.locator("#productId")).toHaveValue(product.id)
  await expect(orderSelect).toHaveValue(order.id); await expect(projectSelect).toHaveValue(project.id)
  await page.unroute("**/dashboard/operations*")
  await projectField.getByRole("button", { name: "Réessayer", exact: true }).click()
  await expect(save).toBeEnabled()
  await database.customerOrder.update({ where: { id: order.id }, data: { status: "CANCELLED" } })
  await orderSearch.fill("recheck changed selection")
  await expect(orderField.getByRole("alert").filter({ hasText: "Le choix n’a pas pu être vérifié." })).toBeVisible()
  await expect(save).toBeDisabled(); await expect(form.locator("#quantity")).toHaveValue("2")
  expect(await database.stockReservation.count({ where: { companyId: company.id } })).toBe(0)
  await orderSearch.fill(replacement.number)
  await expect(orderSelect.locator("option").filter({ hasText: replacement.number })).toHaveCount(1)
  await orderSelect.selectOption(replacement.id); await expect(save).toBeEnabled(); await save.click()
  await expect.poll(() => database.stockReservation.count({ where: { companyId: company.id } })).toBe(1)
  expect(await database.stockReservation.findFirstOrThrow({ where: { companyId: company.id } })).toMatchObject({ customerOrderId: replacement.id, projectId: project.id, warehouseId: warehouse.id, productId: product.id, quantity: 2, status: "ACTIVE" })
  expect(await database.inventoryItem.findUniqueOrThrow({ where: { warehouseId_productId: { warehouseId: warehouse.id, productId: product.id } } })).toMatchObject({ quantity: 10, reservedQuantity: 2 })
  expect(await database.auditLog.count({ where: { userId: user.id, action: "CREATE_STOCK_RESERVATION" } })).toBe(1)
  expect(await database.stockMovement.count({ where: { companyId: company.id, type: "RESERVE" } })).toBe(1)
  expect(await database.emailDelivery.count({ where: { companyId: company.id } })).toBe(0)
  expect(errors).toEqual([])
})
