import { randomUUID } from "node:crypto"
import { PrismaClient } from "@prisma/client"
import { expect, test, type Page } from "@playwright/test"
import { hashPassword } from "../../src/lib/auth/password-core"

const database = new PrismaClient()
test.afterAll(async () => { await database.$disconnect() })

async function setup(surface: string) {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(surface)) throw new Error("La recette Ticket SAV d’intervention exige une SQLite fictive isolée")
  const password = process.env.E2E_USER_PASSWORD || "RecetteSolide2026"
  const company = await database.company.create({ data: { name: "Fictional intervention ticket choices" } })
  await database.saasSubscription.create({ data: { companyId: company.id, plan: "RESEAU", status: "ACTIVE", seatQuantity: 10 } })
  const email = `intervention-ticket-${surface}-${randomUUID()}@example.test`
  const user = await database.user.create({ data: { companyId: company.id, email, emailVerified: new Date(), passwordHash: await hashPassword(password) } })
  const membership = await database.membership.create({ data: { companyId: company.id, userId: user.id, role: "OWNER", status: "ACTIVE" } })
  const agency = await database.agency.create({ data: { companyId: company.id, code: "TICKET", name: "Fictional ticket agency" } })
  await database.agencyMembership.create({ data: { agencyId: agency.id, membershipId: membership.id } })
  const client = await database.client.create({ data: { companyId: company.id, name: "Fictional intervention client" } })
  const site = await database.customerSite.create({ data: { companyId: company.id, clientId: client.id, agencyId: agency.id, label: "Fictional original ticket site", address1: "Fictional address" } })
  const otherSite = await database.customerSite.create({ data: { companyId: company.id, clientId: client.id, agencyId: agency.id, label: "Fictional replacement ticket site", address1: "Fictional other address" } })
  await database.serviceTicket.createMany({ data: Array.from({ length: 200 }, (_, index) => ({ companyId: company.id, clientId: client.id, siteId: site.id,
    number: `TICKET-${String(index).padStart(3, "0")}`, title: `Fictional intervention ticket ${String(index).padStart(3, "0")}`, description: "Fictional description", priority: "NORMAL" })) })
  const last = await database.serviceTicket.create({ data: { companyId: company.id, clientId: client.id, siteId: site.id, number: "TICKET-200",
    title: "Fictional intervention ticket 200", description: "Fictional description", priority: "LOW" } })
  const other = await database.serviceTicket.create({ data: { companyId: company.id, clientId: client.id, siteId: otherSite.id, number: "OTHER-TICKET",
    title: "Fictional replacement site ticket", description: "Fictional description" } })
  return { companyId: company.id, email, password, site, otherSite, last, other }
}

async function openIntervention(page: Page, fixture: Awaited<ReturnType<typeof setup>>) {
  await page.context().clearCookies()
  await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(fixture.email)
  await page.getByLabel("Mot de passe", { exact: true }).fill(fixture.password)
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto("/dashboard/operations?tab=planning&create=1")
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  const composer = page.getByTestId("operation-composer")
  await composer.getByRole("combobox", { name: "Type d’opération", exact: true }).click()
  await page.getByRole("option", { name: "Intervention", exact: true }).click()
  const form = composer.locator("form")
  await expect(form.locator("#ticketId")).toBeDisabled()
  await form.getByRole("textbox", { name: "Rechercher un site à rattacher", exact: true }).fill(fixture.site.label)
  await expect(form.locator("#siteId option").filter({ hasText: fixture.site.label })).toHaveCount(1)
  await form.locator("#siteId").selectOption(fixture.site.id)
  await form.locator("#title").fill("Fictional retained intervention request")
  await form.locator("#scheduledStart").fill("2030-06-20T10:00")
  await form.locator("#scheduledEnd").fill("2030-06-20T11:00")
  return form
}

test("Intervention ticket choices search all 201 tickets and retain input after failed verification or creation", async ({ page }, info) => {
  const fixture = await setup(info.project.name)
  const form = await openIntervention(page, fixture)
  const selected = form.locator("#ticketId"), field = selected.locator("..")
  const search = field.getByRole("textbox", { name: "Rechercher un ticket SAV à rattacher", exact: true })
  const save = form.getByRole("button", { name: "Enregistrer", exact: true })
  await expect(field.getByRole("status")).toHaveText("201 résultats")
  await field.getByRole("button", { name: "Page suivante", exact: true }).click()
  await expect(field.getByText("Page 2 sur 9", { exact: true })).toBeVisible()
  await field.getByRole("button", { name: "Page précédente", exact: true }).click()
  await search.fill(fixture.last.title)
  await expect(field.getByRole("status")).toHaveText("1 résultat")
  await selected.selectOption(fixture.last.id)
  await search.fill("No matching fictional ticket")
  await expect(field.getByRole("status")).toHaveText("0 résultats")
  await expect(selected).toHaveValue(fixture.last.id)
  await expect(save).toBeEnabled()
  await search.fill("")
  await expect(field.getByRole("status")).toHaveText("201 résultats")
  await field.getByRole("button", { name: "Page suivante", exact: true }).click()
  await expect(field.getByText("Page 2 sur 9", { exact: true })).toBeVisible()
  await expect(selected).toHaveValue(fixture.last.id)
  await page.route("**/dashboard/operations*", route => route.request().method() === "POST" ? route.abort("failed") : route.continue())
  await search.fill("Fictional interrupted ticket query")
  await expect(field.getByRole("alert").filter({ hasText: "Impossible d’actualiser la liste." })).toBeVisible()
  await expect(selected).toHaveValue(fixture.last.id)
  await expect(save).toBeDisabled()
  await expect(form.locator("#title")).toHaveValue("Fictional retained intervention request")
  await expect(form.locator("#scheduledStart")).toHaveValue("2030-06-20T10:00")
  await page.unroute("**/dashboard/operations*")
  await search.fill(fixture.last.title)
  await expect(field.getByRole("status")).toHaveText("1 résultat")
  await expect(save).toBeEnabled()
  const target = await database.serviceTicket.findFirstOrThrow({ where: { companyId: fixture.companyId, number: "TICKET-000" } })
  await database.serviceTicket.update({ where: { id: fixture.last.id }, data: { status: "MERGED", mergedIntoTicketId: target.id } })
  await save.click()
  await expect(page.locator("[data-sonner-toast]")).toContainText("Ticket introuvable")
  await expect(field.getByRole("alert").filter({ hasText: "La référence choisie n’est plus disponible" })).toBeVisible()
  await expect(selected).toHaveValue(fixture.last.id)
  await expect(save).toBeDisabled()
  expect(await database.fieldIntervention.count({ where: { companyId: fixture.companyId } })).toBe(0)
  await expect(form.locator("#title")).toHaveValue("Fictional retained intervention request")
  await expect(form.locator("#scheduledEnd")).toHaveValue("2030-06-20T11:00")
  await selected.selectOption("")
  await expect(save).toBeEnabled()
  await save.click()
  await expect.poll(() => database.fieldIntervention.count({ where: { companyId: fixture.companyId, siteId: fixture.site.id, ticketId: null, title: "Fictional retained intervention request" } })).toBe(1)
})

test("Intervention ticket choices recheck a changed site without clearing the selected ticket or the form", async ({ page }, info) => {
  const fixture = await setup(info.project.name)
  const form = await openIntervention(page, fixture)
  const selected = form.locator("#ticketId"), field = selected.locator("..")
  const search = field.getByRole("textbox", { name: "Rechercher un ticket SAV à rattacher", exact: true })
  const save = form.getByRole("button", { name: "Enregistrer", exact: true })
  await search.fill(fixture.last.title)
  await expect(field.getByRole("status")).toHaveText("1 résultat")
  await selected.selectOption(fixture.last.id)
  await expect(save).toBeEnabled()
  await form.getByRole("textbox", { name: "Rechercher un site à rattacher", exact: true }).fill(fixture.otherSite.label)
  await expect(form.locator("#siteId option").filter({ hasText: fixture.otherSite.label })).toHaveCount(1)
  await form.locator("#siteId").selectOption(fixture.otherSite.id)
  await expect(field.getByRole("alert").filter({ hasText: "La référence choisie n’est plus disponible" })).toBeVisible()
  await expect(selected).toHaveValue(fixture.last.id)
  await expect(save).toBeDisabled()
  await expect(form.locator("#title")).toHaveValue("Fictional retained intervention request")
  await expect(form.locator("#scheduledStart")).toHaveValue("2030-06-20T10:00")
  await selected.selectOption("")
  await expect(save).toBeEnabled()
  await search.fill(fixture.other.title)
  await expect(field.getByRole("status")).toHaveText("1 résultat")
  await selected.selectOption(fixture.other.id)
  await expect(save).toBeEnabled()
  await expect(form.locator("#scheduledEnd")).toHaveValue("2030-06-20T11:00")
  await save.click()
  await expect.poll(() => database.fieldIntervention.count({ where: { companyId: fixture.companyId, siteId: fixture.otherSite.id, ticketId: fixture.other.id, title: "Fictional retained intervention request" } })).toBe(1)
})
