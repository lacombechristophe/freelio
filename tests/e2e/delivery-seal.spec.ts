import { PrismaClient } from "@prisma/client"
import { expect, test } from "@playwright/test"

const database = new PrismaClient()
test.afterAll(async () => { await database.$disconnect() })

test("reserved stock, delivery and captured acknowledgement retain their history", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette Livraison exige une SQLite fictive isolée")
  const source = await database.user.findUniqueOrThrow({ where: { email: `purchase-creation-${info.project.name}@example.test` }, select: { passwordHash: true } })
  const company = await database.company.create({ data: { name: "Original fictional delivery sender" } })
  await database.saasSubscription.create({ data: { companyId: company.id, plan: "RESEAU", status: "ACTIVE", seatQuantity: 10 } })
  const email = `delivery-seal-${info.project.name}@example.test`
  const user = await database.user.create({ data: { companyId: company.id, email, emailVerified: new Date(), passwordHash: source.passwordHash } })
  await database.membership.create({ data: { companyId: company.id, userId: user.id, role: "OWNER", status: "ACTIVE" } })
  const client = await database.client.create({ data: { companyId: company.id, name: "Original fictional delivery recipient" } })
  const project = await database.project.create({ data: { companyId: company.id, clientId: client.id, name: "Fictional delivery project" } })
  const product = await database.product.create({ data: { companyId: company.id, sku: "DELIVERY", label: "Fictional delivered product" } })
  const warehouse = await database.warehouse.create({ data: { companyId: company.id, name: "Fictional warehouse", code: "DELIVERY" } })
  await database.inventoryItem.create({ data: { companyId: company.id, warehouseId: warehouse.id, productId: product.id, quantity: 3 } })
  const order = await database.customerOrder.create({ data: { companyId: company.id, clientId: client.id, projectId: project.id, number: `DELIVERY-${info.project.name}`, totalHtCents: 300, totalTtcCents: 300,
    lines: { create: { productId: product.id, label: "Original fictional delivery line", quantity: 3, unitPriceCents: 100, tvaRate: 0 } },
  }, include: { lines: true } })
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message))
  await page.context().clearCookies(); await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(email)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  async function composer(kind: string) {
    await page.goto("/dashboard/operations?tab=orders&create=1")
    await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
    const target = page.getByTestId("operation-composer")
    await target.getByRole("combobox", { name: "Type d’opération", exact: true }).click()
    await page.getByRole("option", { name: kind, exact: true }).click()
    return target.locator("form")
  }
  const reserve = await composer("Réservation de stock")
  await reserve.locator("#warehouseId").selectOption(warehouse.id)
  await reserve.locator("#productId").selectOption(product.id)
  await reserve.locator("#customerOrderId").selectOption(order.id)
  await reserve.locator("#quantity").fill("3")
  await reserve.getByRole("button", { name: "Enregistrer", exact: true }).click()
  await expect(page.getByText("Réservation de stock enregistré.", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Consommer", exact: true }).click()
  await expect(page.getByText("Stock consommé pour le dossier.", { exact: true })).toBeVisible()
  const delivery = await composer("Bon de livraison")
  await delivery.locator("#customerOrderId").selectOption(order.id)
  await delivery.locator("#customerOrderLineId").selectOption(order.lines[0].id)
  await delivery.locator("#quantity").fill("3")
  await delivery.locator("#recipientName").fill("Fictional recipient")
  await delivery.getByRole("button", { name: "Enregistrer", exact: true }).click()
  await expect(page.getByText("Bon de livraison enregistré.", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Faire signer", exact: true }).click()
  const signing = page.getByRole("dialog", { name: "Signer le bon de livraison", exact: true })
  await signing.getByLabel("Nom du réceptionnaire", { exact: true }).fill("Fictional recipient")
  await signing.getByRole("checkbox").check()
  await signing.getByRole("button", { name: "Signer et sceller", exact: true }).click()
  await expect(signing).toBeHidden()
  const note = await database.deliveryNote.findFirstOrThrow({ where: { companyId: company.id } })
  expect(note).toMatchObject({ status: "SIGNED", sealVersion: 1, signatureSha256: expect.stringMatching(/^[a-f0-9]{64}$/) })
  const url = `/api/pdf/livraison/${note.id}`, original = await (await page.request.get(`${url}?screen=1`)).text()
  await database.company.update({ where: { id: company.id }, data: { name: "Changed sender" } })
  await database.client.update({ where: { id: client.id }, data: { name: "Changed recipient" } })
  expect(await (await page.request.get(`${url}?screen=1`)).text()).toBe(original)
  const pdf = await page.request.get(url)
  expect(pdf.ok()).toBe(true); expect((await pdf.body()).subarray(0, 4).toString("ascii")).toBe("%PDF")
  expect(await database.customerOrderLine.findUniqueOrThrow({ where: { id: order.lines[0].id } })).toMatchObject({ deliveredQuantity: 3 })
  expect(await database.inventoryItem.findUniqueOrThrow({ where: { warehouseId_productId: { warehouseId: warehouse.id, productId: product.id } } })).toMatchObject({ quantity: 0, reservedQuantity: 0 })
  await database.deliveryNote.create({ data: { companyId: company.id, customerOrderId: order.id, projectId: project.id, number: "HISTORICAL", status: "SIGNED", signedAt: new Date(), signatureSha256: "a".repeat(64) } })
  await page.reload()
  await expect(page.getByText("Archive historique indisponible", { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
