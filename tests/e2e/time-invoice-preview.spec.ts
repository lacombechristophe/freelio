import { createDatabaseClient } from "@/lib/database-client"
import { expect, test } from "@playwright/test"

const database = createDatabaseClient()
test.afterAll(async () => { await database.$disconnect() })

test("A compiled stale preview preserves a selection hidden by a filter and succeeds only after reload", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("L'édition SQL navigateur exige la recette SQLite isolée")
  const surface = info.project.name, id = `ctimepreview${surface}`, object = `FICTIONAL-PREVIEW-COMPILED-${surface}`, errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  const initial = await database.timeEntry.findUniqueOrThrow({ where: { id } })
  const other = await database.timeEntry.findUniqueOrThrow({ where: { id: `ctimepreviewother${surface}` } })
  await page.context().clearCookies(); await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(`time-preview-${surface}@example.test`)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  expect((await page.goto("/dashboard/factures/temps-non-facture"))?.status()).toBe(200)
  const checkbox = page.locator("label").filter({ hasText: "FICTIONAL-PREVIEW-TIME" }).getByRole("checkbox")
  async function fillForm() {
    await checkbox.check()
    await page.getByLabel("Taux horaire HT (€)", { exact: true }).fill("100")
    await page.getByLabel("Échéance", { exact: true }).fill("2030-02-01")
    await page.getByLabel("Objet optionnel", { exact: true }).fill(object)
    await page.getByLabel("Lignes de facture", { exact: true }).selectOption("DETAIL")
  }
  const total = page.locator("aside").getByText("Total HT", { exact: true }).locator("..")
  await fillForm()
  await expect(total).toContainText("100,00")
  await page.getByLabel("Projet", { exact: true }).selectOption(other.projectId)
  await expect(checkbox).toHaveCount(0)
  await expect(total).toContainText("100,00")
  // A completed edit of this disposable fixture precedes submission. No trigger
  // or action mock is involved; the displayed page still contains the old time.
  await database.timeEntry.update({ where: { id }, data: { durationSec: 7200 } })
  await page.getByRole("button", { name: "Créer la facture brouillon", exact: true }).click()
  await expect(page.getByText("Les temps ont changé pendant la création de la facture. Rechargez la page puis réessayez.", { exact: true })).toBeVisible()
  await expect(page.getByLabel("Projet", { exact: true })).toHaveValue(other.projectId)
  await expect(total).toContainText("100,00")
  await expect(page.getByLabel("Taux horaire HT (€)", { exact: true })).toHaveValue("100")
  await expect(page.getByLabel("Échéance", { exact: true })).toHaveValue("2030-02-01")
  await expect(page.getByLabel("Objet optionnel", { exact: true })).toHaveValue(object)
  await expect(page.getByLabel("Lignes de facture", { exact: true })).toHaveValue("DETAIL")
  await page.getByLabel("Projet", { exact: true }).selectOption("ALL")
  await expect(checkbox).toBeChecked()
  expect(await database.timeEntry.findUniqueOrThrow({ where: { id } })).toEqual({ ...initial, durationSec: 7200 })
  expect(await database.invoice.count({ where: { object } })).toBe(0)
  expect(await database.auditLog.count({ where: { userId: (await database.user.findUniqueOrThrow({ where: { email: `time-preview-${surface}@example.test` } })).id, action: "CREATE_INVOICE_FROM_TIME" } })).toBe(0)
  await page.reload()
  await fillForm()
  await expect(total).toContainText("200,00")
  await page.getByRole("button", { name: "Créer la facture brouillon", exact: true }).click()
  await page.waitForURL(url => /^\/dashboard\/factures\/c[a-z0-9]+$/.test(url.pathname), { timeout: 60_000 })
  const invoiceId = new URL(page.url()).pathname.split("/").at(-1)!
  expect(await database.invoice.findUniqueOrThrow({ where: { id: invoiceId } })).toMatchObject({ status: "DRAFT", object, totalHtCents: 20000 })
  expect(await database.timeEntry.findUniqueOrThrow({ where: { id } })).toEqual({ ...initial, durationSec: 7200, invoiceId })
  expect(await database.timeEntry.findUniqueOrThrow({ where: { id: other.id } })).toEqual(other)
  expect(await database.auditLog.count({ where: { resourceId: invoiceId, action: "CREATE_INVOICE_FROM_TIME" } })).toBe(1)
  expect(errors).toEqual([])
})
