import { expect, test } from "@playwright/test"

test("filters, claims, archives and restores a local conversation without losing its message", async ({ page }, info) => {
  await page.context().clearCookies()
  await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(`inbox-management-${info.project.name}@example.test`)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto("/dashboard/communications")
  const thread = page.locator("button[data-selected]").filter({ hasText: "UIQA Inbox management" })
  const state = page.getByLabel("Conversations affichées", { exact: true })
  const assignment = page.getByLabel("Prise en charge", { exact: true })
  await page.getByLabel("Boîte de réception", { exact: true }).selectOption({ label: "Fictional inbox mailbox" })
  await assignment.selectOption("UNASSIGNED")
  await expect(thread).toBeVisible()
  await thread.click()
  await page.getByRole("button", { name: "Prendre en charge", exact: true }).click()
  await expect(page.getByText("Aucune conversation", { exact: true })).toBeVisible()
  await assignment.selectOption("ME")
  await expect(thread).toBeVisible()
  await state.selectOption("OPEN")
  await thread.click()
  await expect(page.getByText("Pris en charge par vous", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Clore", exact: true }).click()
  await expect(page.getByText("Aucune conversation", { exact: true })).toBeVisible()
  await state.selectOption("CLOSED")
  await expect(thread).toBeVisible()
  await thread.click()
  await page.getByRole("button", { name: "Archiver", exact: true }).click()
  await expect(page.getByText("Aucune conversation", { exact: true })).toBeVisible()
  await state.selectOption("ARCHIVED")
  await expect(thread).toBeVisible()
  await thread.click()
  await expect(page.locator("article").getByText("Fictional inbox management message", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Restaurer", exact: true }).click()
  await expect(page.getByText("Aucune conversation", { exact: true })).toBeVisible()
  await state.selectOption("OPEN")
  await expect(thread).toBeVisible()
  await thread.click()
  await page.getByRole("button", { name: "Libérer ma prise en charge", exact: true }).click()
  await expect(page.getByText("Aucune conversation", { exact: true })).toBeVisible()
  await assignment.selectOption("UNASSIGNED")
  await expect(thread).toBeVisible()
  await thread.click()
  await expect(page.locator("article").getByText("Fictional inbox management message", { exact: true })).toBeVisible()
  const main = page.locator("#dashboard-main")
  expect(await main.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
})
