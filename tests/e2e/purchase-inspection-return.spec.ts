import { PrismaClient } from "@prisma/client"
import { expect, test } from "@playwright/test"

const database = new PrismaClient()
test.afterAll(async () => { await database.$disconnect() })

test("supplier inspection preserves delivery observations through return and credit", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette exige une SQLite fictive isolée")
  const surface = info.project.name, email = `purchase-inspection-${surface}@example.test`
  const source = await database.user.findUniqueOrThrow({ where: { email: `purchase-creation-${surface}@example.test` }, select: { passwordHash: true } })
  const company = await database.company.create({ data: { name: `Fictional supplier inspection ${surface}` } })
  await database.saasSubscription.create({ data: { companyId: company.id, plan: "RESEAU", status: "ACTIVE", seatQuantity: 10 } })
  const user = await database.user.create({ data: { companyId: company.id, email, emailVerified: new Date(), passwordHash: source.passwordHash } })
  await database.membership.create({ data: { companyId: company.id, userId: user.id, role: "OWNER", status: "ACTIVE" } })
  const supplier = await database.supplier.create({ data: { companyId: company.id, name: "Fictional inspection supplier" } })
  const product = await database.product.create({ data: { companyId: company.id, sku: "INSPECTED", label: "Fictional inspected product" } })
  const warehouse = await database.warehouse.create({ data: { companyId: company.id, code: "INSPECTED", name: "Fictional inspection warehouse" } })
  const order = await database.purchaseOrder.create({ data: { companyId: company.id, supplierId: supplier.id, number: `INSPECTED-${surface}`, status: "SENT", totalHtCents: 300,
    lines: { create: { productId: product.id, label: "Fictional inspected product", quantity: 3, unitPriceCents: 100 } },
  }, include: { lines: true } })
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message))
  await page.context().clearCookies(); await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(email)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto("/dashboard/operations?tab=stock")
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  const directory = page.getByRole("region", { name: "Commandes fournisseur", exact: true })
  await directory.getByRole("button", { name: "Réceptionner", exact: true }).click()
  const receipt = page.getByRole("dialog", { name: "Réception fournisseur", exact: true })
  await receipt.getByLabel("Ligne", { exact: true }).selectOption(order.lines[0].id)
  await receipt.getByLabel("Dépôt", { exact: true }).selectOption(warehouse.id)
  await receipt.getByLabel("Quantité livrée", { exact: true }).fill("3")
  await receipt.getByLabel("Dont rejetée", { exact: true }).fill("2")
  await receipt.getByLabel("Type d’anomalie", { exact: true }).selectOption("QUALITY")
  await receipt.getByRole("button", { name: "Enregistrer la réception", exact: true }).click()
  await expect(receipt).toBeHidden()
  expect(await database.inventoryItem.findUniqueOrThrow({ where: { warehouseId_productId: { warehouseId: warehouse.id, productId: product.id } } })).toMatchObject({ quantity: 1 })
  await directory.getByRole("button", { name: "Traiter", exact: true }).click()
  const inspection = page.getByRole("dialog", { name: "Traiter l’anomalie fournisseur", exact: true })
  await inspection.getByLabel("Décision", { exact: true }).selectOption("ACCEPTED")
  await inspection.getByLabel("Détail / preuve", { exact: true }).fill("Fictional inspection accepted both units")
  await inspection.getByRole("button", { name: "Valider", exact: true }).click()
  await expect(inspection).toBeHidden()
  expect(await database.purchaseIssue.findFirstOrThrow({ where: { companyId: company.id } })).toMatchObject({ status: "RESOLVED", resolutionKind: "ACCEPTED" })
  await directory.getByRole("button", { name: "Retour fournisseur", exact: true }).click()
  const returned = page.getByRole("dialog", { name: "Retour fournisseur", exact: true })
  await returned.getByLabel("Ligne reçue", { exact: true }).selectOption(order.lines[0].id)
  await returned.getByLabel("Dépôt", { exact: true }).selectOption(warehouse.id)
  await returned.getByLabel("Quantité", { exact: true }).fill("3")
  await returned.getByLabel("Motif", { exact: true }).fill("Fictional return after inspection")
  await returned.getByRole("button", { name: "Expédier le retour", exact: true }).click()
  await expect(returned).toBeHidden()
  const history = await database.supplierReturn.findFirstOrThrow({ where: { companyId: company.id } })
  await directory.getByRole("button", { name: "Enregistrer l’avoir", exact: true }).click()
  const credit = page.getByRole("dialog", { name: `Avoir du retour ${history.number}`, exact: true })
  await credit.getByLabel("Référence de l’avoir", { exact: true }).fill("FICTIONAL-CREDIT")
  await credit.getByRole("button", { name: "Enregistrer l’avoir", exact: true }).click()
  await expect(credit).toBeHidden()
  expect(await database.supplierReturn.findUniqueOrThrow({ where: { id: history.id } })).toMatchObject({ quantity: 3, status: "CREDITED", creditReference: "FICTIONAL-CREDIT" })
  expect(await database.inventoryItem.findUniqueOrThrow({ where: { warehouseId_productId: { warehouseId: warehouse.id, productId: product.id } } })).toMatchObject({ quantity: 0 })
  expect(await database.goodsReceiptLine.findFirstOrThrow({ where: { goodsReceipt: { companyId: company.id } } })).toMatchObject({ quantity: 3, acceptedQuantity: 1, rejectedQuantity: 2 })
  expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(4)
  expect(errors).toEqual([])
})
