import { createDatabaseClient } from "@/lib/database-client"
import { expect, test } from "@playwright/test"

const database = createDatabaseClient()
test.afterAll(async () => { await database.$disconnect() })

test("purchase drafts preserve input, reject stale edits and retain canceled history", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette Création Achat exige une SQLite fictive isolée")
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message))
  const surface = info.project.name, productId = `cpurchaseintegrityproduct${surface}`, projectId = `cpurchaseintegrityproject${surface}`, clientId = `cpurchaseintegrityclient${surface}`
  const product = await database.product.findUniqueOrThrow({ where: { id: productId } })
  const user = await database.user.findUniqueOrThrow({ where: { email: `purchase-creation-${surface}@example.test` }, select: { id: true } })
  await page.context().clearCookies(); await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(`purchase-creation-${surface}@example.test`)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto("/dashboard/operations?tab=stock")
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  await page.getByRole("button", { name: "Nouvelle commande", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Nouvelle commande fournisseur", exact: true })
  await dialog.getByLabel("Fournisseur de la commande", { exact: true }).selectOption(`cpurchaseintegritysupplier${surface}`)
  await dialog.getByLabel("Chantier de la commande", { exact: true }).selectOption(projectId)
  await dialog.getByLabel("Produit fournisseur 1", { exact: true }).selectOption(productId)
  await dialog.getByLabel("Quantité fournisseur 1", { exact: true }).fill("2")
  await dialog.getByLabel("Prix fournisseur 1", { exact: true }).fill("12.34")
  await dialog.getByLabel("Libellé fournisseur 1", { exact: true }).fill("Fictional preserved integrity line")
  await dialog.getByLabel("Instructions fournisseur", { exact: true }).fill("Fictional preserved integrity instructions")
  const save = dialog.getByRole("button", { name: "Créer le brouillon", exact: true })
  await expect(save).toBeEnabled()
  await database.project.update({ where: { id: projectId }, data: { clientId: `cpurchaseintegrityforeignclient${surface}` } })
  await save.click()
  await expect(page.getByText("Chantier introuvable", { exact: true })).toBeVisible()
  await expect(dialog).toBeVisible()
  expect(await database.purchaseOrder.count({ where: { companyId: product.companyId } })).toBe(0)
  expect(await database.purchaseOrderLine.count({ where: { purchaseOrder: { companyId: product.companyId } } })).toBe(0)
  expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(0)
  expect((await database.project.findUniqueOrThrow({ where: { id: projectId } })).clientId).toBe(`cpurchaseintegrityforeignclient${surface}`)
  await database.project.update({ where: { id: projectId }, data: { clientId } })
  await database.product.update({ where: { id: productId }, data: { active: false } })
  await save.click()
  await expect(page.getByText("Un produit fournisseur est introuvable", { exact: true })).toBeVisible()
  expect(await database.purchaseOrder.count({ where: { companyId: product.companyId } })).toBe(0)
  expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(0)
  expect((await database.product.findUniqueOrThrow({ where: { id: productId } })).active).toBe(false)
  await expect(dialog.getByLabel("Chantier de la commande", { exact: true })).toHaveValue(projectId)
  await expect(dialog.getByLabel("Produit fournisseur 1", { exact: true })).toHaveValue(productId)
  await expect(dialog.getByLabel("Quantité fournisseur 1", { exact: true })).toHaveValue("2")
  await expect(dialog.getByLabel("Prix fournisseur 1", { exact: true })).toHaveValue("12.34")
  await expect(dialog.getByLabel("Libellé fournisseur 1", { exact: true })).toHaveValue("Fictional preserved integrity line")
  await expect(dialog.getByLabel("Instructions fournisseur", { exact: true })).toHaveValue("Fictional preserved integrity instructions")
  await database.product.update({ where: { id: productId }, data: { active: true } })
  await save.click(); await expect(dialog).toBeHidden()
  const order = await database.purchaseOrder.findFirstOrThrow({ where: { companyId: product.companyId }, include: { lines: true } })
  expect(order).toMatchObject({ projectId, status: "DRAFT", totalHtCents: 2468, lines: [{ productId, label: "Fictional preserved integrity line", quantity: 2, unitPriceCents: 1234 }] })
  expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(1)
  await database.purchaseOrder.createMany({ data: Array.from({ length: 101 }, (_, index) => ({ companyId: product.companyId, supplierId: order.supplierId, projectId, number: `DIRECTORY-CLOSED-${surface}-${index}`, status: "RECEIVED", createdAt: new Date("2035-01-01T00:00:00Z") })) })
  await page.reload()
  const directory = page.getByRole("region", { name: "Commandes fournisseur", exact: true })
  await expect(directory.getByRole("status")).toHaveText("102 résultats")
  await expect(directory.getByRole("link", { name: order.number, exact: true })).toHaveCount(0)
  await directory.getByLabel("Rechercher un achat fournisseur", { exact: true }).fill(order.number)
  await expect(directory.getByRole("status")).toHaveText("1 résultat")
  await expect(directory.getByRole("link", { name: order.number, exact: true })).toBeVisible()
  await directory.getByLabel("État de l’achat", { exact: true }).selectOption("RECEIVED")
  await expect(directory.getByRole("status")).toHaveText("0 résultats")
  await directory.getByLabel("État de l’achat", { exact: true }).selectOption("DRAFT")
  await expect(directory.getByRole("status")).toHaveText("1 résultat")
  await directory.getByRole("button", { name: "Modifier le brouillon", exact: true }).click()
  const listEditor = page.getByRole("dialog", { name: `Modifier ${order.number}`, exact: true })
  await expect(listEditor.getByLabel("Prix fournisseur 1", { exact: true })).toHaveValue("12.34")
  await listEditor.getByRole("button", { name: "Annuler", exact: true }).click()
  await expect(directory.getByLabel("Rechercher un achat fournisseur", { exact: true })).toHaveValue(order.number)
  await page.goto(`/dashboard/operations/achats/${order.id}`)
  await page.getByRole("button", { name: "Modifier le brouillon", exact: true }).click()
  const editor = page.getByRole("dialog", { name: `Modifier ${order.number}`, exact: true })
  await expect(editor.getByLabel("Prix fournisseur 1", { exact: true })).toHaveValue("12.34")
  await expect(editor.getByLabel("Instructions fournisseur", { exact: true })).toHaveValue("Fictional preserved integrity instructions")
  await editor.getByLabel("Quantité fournisseur 1", { exact: true }).fill("3")
  await editor.getByRole("button", { name: "Enregistrer le brouillon", exact: true }).click()
  await expect(editor).toBeHidden()
  expect(await database.purchaseOrder.findUniqueOrThrow({ where: { id: order.id } })).toMatchObject({ status: "DRAFT", totalHtCents: 3702 })
  expect(await database.purchaseOrderLine.findUniqueOrThrow({ where: { id: order.lines[0].id } })).toMatchObject({ quantity: 3, unitPriceCents: 1234 })
  await page.getByRole("button", { name: "Modifier le brouillon", exact: true }).click()
  await editor.getByLabel("Prix fournisseur 1", { exact: true }).fill("99")
  await database.$transaction([
    database.purchaseOrderLine.update({ where: { id: order.lines[0].id }, data: { quantity: 9 } }),
    database.purchaseOrder.update({ where: { id: order.id }, data: { totalHtCents: 11106 } }),
  ])
  await editor.getByRole("button", { name: "Enregistrer le brouillon", exact: true }).click()
  await expect(page.getByText("La commande fournisseur a changé. Rechargez la page avant de réessayer ; votre saisie est conservée.", { exact: true })).toBeVisible()
  await expect(editor.getByLabel("Prix fournisseur 1", { exact: true })).toHaveValue("99")
  expect(await database.purchaseOrder.findUniqueOrThrow({ where: { id: order.id } })).toMatchObject({ totalHtCents: 11106 })
  expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(2)
  await editor.getByRole("button", { name: "Annuler", exact: true }).click()
  await page.reload()
  await page.getByRole("button", { name: "Annuler la commande", exact: true }).click()
  const cancellation = page.getByRole("dialog", { name: `Annuler ${order.number}`, exact: true })
  await expect(cancellation.getByRole("button", { name: "Confirmer l’annulation", exact: true })).toBeDisabled()
  await cancellation.getByLabel("Motif d’annulation", { exact: true }).fill("Fictional requirement withdrawn before transmission")
  await cancellation.getByRole("checkbox").check()
  await cancellation.getByRole("button", { name: "Confirmer l’annulation", exact: true }).click()
  await expect(cancellation).toBeHidden()
  await expect(page.getByRole("button", { name: "Modifier le brouillon", exact: true })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Soumettre", exact: true })).toHaveCount(0)
  expect(await database.purchaseOrder.findUniqueOrThrow({ where: { id: order.id } })).toMatchObject({ status: "CANCELED", totalHtCents: 11106 })
  expect(await database.purchaseOrderLine.findUniqueOrThrow({ where: { id: order.lines[0].id } })).toMatchObject({ quantity: 9, unitPriceCents: 1234 })
  expect(await database.auditLog.findMany({ where: { userId: user.id, action: "CANCEL_PURCHASE_ORDER" } })).toMatchObject([{ payload: { reason: "Fictional requirement withdrawn before transmission", previousStatus: "DRAFT" } }])
  expect(await database.stockMovement.count({ where: { companyId: product.companyId } })).toBe(0)
  expect(await database.emailDelivery.count({ where: { companyId: product.companyId } })).toBe(0)
  expect(errors).toEqual([])
})
