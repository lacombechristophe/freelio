import { PrismaClient } from "@prisma/client"
import { expect, test } from "@playwright/test"

const database = new PrismaClient()
test.afterAll(async () => { await database.$disconnect() })

test("purchase creation refuses changed references and preserves input for recovery", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette Création Achat exige une SQLite fictive isolée")
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message))
  const surface = info.project.name, productId = `cpurchaseintegrityproduct${surface}`, projectId = `cpurchaseintegrityproject${surface}`, clientId = `cpurchaseintegrityclient${surface}`
  const product = await database.product.findUniqueOrThrow({ where: { id: productId } })
  const user = await database.user.findUniqueOrThrow({ where: { email: `purchase-creation-${surface}@example.test` }, select: { id: true } })
  await page.context().clearCookies(); await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(`purchase-creation-${surface}@example.test`)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto("/dashboard/operations?tab=stock")
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  await page.getByRole("button", { name: "Nouvelle commande", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Nouvelle commande fournisseur", exact: true })
  await dialog.getByLabel("Fournisseur de la commande", { exact: true }).selectOption(`cpurchaseintegritysupplier${surface}`)
  await dialog.getByLabel("Chantier de la commande", { exact: true }).selectOption(projectId)
  await dialog.getByLabel("Produit fournisseur 1", { exact: true }).selectOption(productId)
  await dialog.getByLabel("Quantité fournisseur 1", { exact: true }).fill("2")
  await dialog.getByLabel("Prix fournisseur 1", { exact: true }).fill("12.34")
  await dialog.getByLabel("Libellé fournisseur 1", { exact: true }).fill("Fictional preserved integrity line")
  await dialog.getByLabel("Instructions fournisseur", { exact: true }).fill("Fictional preserved integrity instructions")
  const save = dialog.getByRole("button", { name: "Créer le brouillon", exact: true })
  await expect(save).toBeEnabled()
  await database.project.update({ where: { id: projectId }, data: { clientId: `cpurchaseintegrityforeignclient${surface}` } })
  await save.click()
  await expect(page.getByText("Chantier introuvable", { exact: true })).toBeVisible()
  await expect(dialog).toBeVisible()
  expect(await database.purchaseOrder.count({ where: { companyId: product.companyId } })).toBe(0)
  expect(await database.purchaseOrderLine.count({ where: { purchaseOrder: { companyId: product.companyId } } })).toBe(0)
  expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(0)
  expect((await database.project.findUniqueOrThrow({ where: { id: projectId } })).clientId).toBe(`cpurchaseintegrityforeignclient${surface}`)
  await database.project.update({ where: { id: projectId }, data: { clientId } })
  await database.product.update({ where: { id: productId }, data: { active: false } })
  await save.click()
  await expect(page.getByText("Un produit fournisseur est introuvable", { exact: true })).toBeVisible()
  expect(await database.purchaseOrder.count({ where: { companyId: product.companyId } })).toBe(0)
  expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(0)
  expect((await database.product.findUniqueOrThrow({ where: { id: productId } })).active).toBe(false)
  await expect(dialog.getByLabel("Chantier de la commande", { exact: true })).toHaveValue(projectId)
  await expect(dialog.getByLabel("Produit fournisseur 1", { exact: true })).toHaveValue(productId)
  await expect(dialog.getByLabel("Quantité fournisseur 1", { exact: true })).toHaveValue("2")
  await expect(dialog.getByLabel("Prix fournisseur 1", { exact: true })).toHaveValue("12.34")
  await expect(dialog.getByLabel("Libellé fournisseur 1", { exact: true })).toHaveValue("Fictional preserved integrity line")
  await expect(dialog.getByLabel("Instructions fournisseur", { exact: true })).toHaveValue("Fictional preserved integrity instructions")
  await database.product.update({ where: { id: productId }, data: { active: true } })
  await save.click(); await expect(dialog).toBeHidden()
  const order = await database.purchaseOrder.findFirstOrThrow({ where: { companyId: product.companyId }, include: { lines: true } })
  expect(order).toMatchObject({ projectId, status: "DRAFT", totalHtCents: 2468, lines: [{ productId, label: "Fictional preserved integrity line", quantity: 2, unitPriceCents: 1234 }] })
  expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(1)
  expect(await database.stockMovement.count({ where: { companyId: product.companyId } })).toBe(0)
  expect(await database.emailDelivery.count({ where: { companyId: product.companyId } })).toBe(0)
  expect(errors).toEqual([])
})
