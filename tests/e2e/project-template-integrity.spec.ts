import { randomUUID } from "node:crypto"
import { PrismaClient } from "@prisma/client"
import { expect, test } from "@playwright/test"

const database = new PrismaClient()
test.afterAll(async () => { await database.$disconnect() })

test("project templates hide foreign prerequisites and preserve drafts after a stale transition", async ({ page }, info) => {
  if (process.env.RECIPE_ISOLATED !== "true" || !process.env.DATABASE_URL?.startsWith("file:") || process.env.PLAYWRIGHT_BASE_URL || !["desktop", "mobile"].includes(info.project.name)) throw new Error("La recette Modèles de chantier exige une SQLite fictive isolée")
  const source = await database.user.findUniqueOrThrow({ where: { email: `purchase-creation-${info.project.name}@example.test` }, select: { passwordHash: true } })
  const company = await database.company.create({ data: { name: "Fictional template browser company" } })
  await database.saasSubscription.create({ data: { companyId: company.id, plan: "RESEAU", status: "ACTIVE", seatQuantity: 10 } })
  const email = `template-browser-${info.project.name}-${randomUUID()}@example.test`
  const user = await database.user.create({ data: { companyId: company.id, email, emailVerified: new Date(), passwordHash: source.passwordHash } })
  const membership = await database.membership.create({ data: { companyId: company.id, userId: user.id, role: "OWNER", status: "ACTIVE" } })
  const template = await database.projectTemplate.create({ data: { companyId: company.id, name: "Fictional browser template" } })
  const foreignCompany = await database.company.create({ data: { name: "Fictional unrelated template company" } })
  const foreignTemplate = await database.projectTemplate.create({ data: { companyId: foreignCompany.id, name: "Fictional foreign browser template" } })
  const foreignStep = await database.projectTemplateStep.create({ data: { templateId: foreignTemplate.id, title: "FOREIGN-TEMPLATE-PREREQUISITE-SECRET" } })
  await database.projectTemplateStep.create({ data: { templateId: template.id, title: "Fictional unavailable prerequisite", dependsOnStepId: foreignStep.id } })
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  await page.context().clearCookies()
  await page.goto("/auth/login")
  await page.getByLabel("Adresse e-mail professionnelle").fill(email)
  await page.getByLabel("Mot de passe", { exact: true }).fill(process.env.E2E_USER_PASSWORD || "RecetteSolide2026")
  await page.getByRole("button", { name: "Se connecter", exact: true }).click()
  await page.waitForURL(url => url.pathname === "/dashboard", { timeout: 60_000 })
  await page.goto("/dashboard/projets")
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  await page.getByRole("button", { name: "Modèles", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Modèles de chantier", exact: true })
  const row = dialog.locator("div.rounded-xl.border.p-4").filter({ has: page.getByText(template.name, { exact: true }) })
  await expect(row).toContainText("Prérequis indisponible")
  expect(await page.content()).not.toContain(foreignStep.title)
  expect(await page.content()).not.toContain(foreignStep.id)
  await dialog.getByLabel("Nom", { exact: true }).fill("Fictional template draft to keep")
  await dialog.getByLabel("Description", { exact: true }).fill("Fictional unsaved description")
  const current = await database.projectTemplate.update({ where: { id: template.id }, data: { description: "Fictional concurrent edit", updatedAt: new Date(template.updatedAt.getTime() + 1000) } })
  await row.getByRole("button", { name: "Désactiver", exact: true }).click()
  await expect(page.getByText("Le modèle de chantier a changé. Rechargez la page puis réessayez ; votre saisie est conservée.", { exact: true })).toBeVisible()
  await expect(dialog.getByLabel("Nom", { exact: true })).toHaveValue("Fictional template draft to keep")
  await expect(dialog.getByLabel("Description", { exact: true })).toHaveValue("Fictional unsaved description")
  expect(await database.projectTemplate.findUniqueOrThrow({ where: { id: template.id } })).toEqual(current)
  expect(await database.auditLog.count({ where: { userId: user.id } })).toBe(0)
  await dialog.getByRole("button", { name: "Fermer", exact: true }).click()
  await page.reload()
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  await page.getByRole("button", { name: "Modèles", exact: true }).click()
  await row.getByRole("button", { name: "Désactiver", exact: true }).click()
  await expect(row.getByRole("button", { name: "Réactiver", exact: true })).toBeEnabled()
  expect((await database.projectTemplate.findUniqueOrThrow({ where: { id: template.id } })).active).toBe(false)
  await row.getByRole("button", { name: "Réactiver", exact: true }).click()
  await expect(row.getByRole("button", { name: "Désactiver", exact: true })).toBeEnabled()
  expect((await database.projectTemplate.findUniqueOrThrow({ where: { id: template.id } })).active).toBe(true)
  expect(await database.auditLog.count({ where: { userId: user.id, resourceId: template.id, action: "UPDATE_PROJECT_TEMPLATE_STATUS" } })).toBe(2)

  await dialog.getByRole("button", { name: "Fermer", exact: true }).click()
  await database.membership.update({ where: { id: membership.id }, data: { role: "SERVICE" } })
  await page.reload()
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === "true")
  await page.getByRole("button", { name: "Modèles", exact: true }).click()
  await expect(row.getByRole("button", { name: "Désactiver", exact: true })).toBeDisabled()
  await expect(dialog.getByRole("button", { name: "Créer le modèle", exact: true })).toBeDisabled()
  await expect(dialog.getByLabel("Nom", { exact: true })).toBeDisabled()
  expect(errors).toEqual([])
})
