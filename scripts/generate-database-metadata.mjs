#!/usr/bin/env node
import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"
import helper from "@prisma/generator-helper"

const { generatorHandler } = helper

generatorHandler({
  onManifest() { return { prettyName: "Freelio database metadata", defaultOutput: "../src/generated/schema-metadata.ts" } },
  async onGenerate({ dmmf, generator }) {
    const output = generator.output.value
    const models = dmmf.datamodel.models.map(({ name, dbName, fields }) => ({ name, dbName: dbName ?? null,
      fields: fields.map(({ name, dbName, kind, type, isRequired, isList }) => ({ name, dbName: dbName ?? null, kind, type, isRequired, isList })),
    }))
    await mkdir(path.dirname(output), { recursive: true })
    const definition = "type Model = { name: string; dbName: string | null; fields: { name: string; dbName: string | null; kind: string; type: string; isRequired: boolean; isList: boolean }[] }\n"
    await writeFile(output, `// Generated by prisma generate; do not edit.\n${definition}export const databaseModels: readonly Model[] = ${JSON.stringify(models)}\n`)
  },
})
